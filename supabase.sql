create table if not exists public.finance_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('income','expense','saving')),
  category text not null,
  description text not null,
  amount numeric(12,2) not null check (amount > 0),
  entry_date date not null default current_date,
  created_at timestamptz not null default now()
);
create index if not exists finance_entries_user_date_idx on public.finance_entries(user_id, entry_date desc);
alter table public.finance_entries enable row level security;
drop policy if exists "Users can read own finance entries" on public.finance_entries;
create policy "Users can read own finance entries" on public.finance_entries for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users can add own finance entries" on public.finance_entries;
create policy "Users can add own finance entries" on public.finance_entries for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can update own finance entries" on public.finance_entries;
create policy "Users can update own finance entries" on public.finance_entries for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Users can delete own finance entries" on public.finance_entries;
create policy "Users can delete own finance entries" on public.finance_entries for delete to authenticated using ((select auth.uid()) = user_id);

grant select, insert, update, delete on public.finance_entries to authenticated;
grant usage, select on sequence public.finance_entries_id_seq to authenticated;

create table if not exists public.finance_settings (
  user_id uuid primary key references auth.users(id) on delete cascade,
  wedding_target numeric(12,2) not null default 0,
  emergency_target numeric(12,2) not null default 0,
  updated_at timestamptz not null default now()
);
alter table public.finance_settings enable row level security;
drop policy if exists "Users can read own finance settings" on public.finance_settings;
create policy "Users can read own finance settings" on public.finance_settings for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users can insert own finance settings" on public.finance_settings;
create policy "Users can insert own finance settings" on public.finance_settings for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can update own finance settings" on public.finance_settings;
create policy "Users can update own finance settings" on public.finance_settings for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
grant select, insert, update on public.finance_settings to authenticated;
